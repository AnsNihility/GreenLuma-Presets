<#
.SYNOPSIS
    Builds the release archive and updates update.xml for the auto-updater.

.DESCRIPTION
    1. Reads the version from GreenLumaPresets.csproj
    2. Publishes a self-contained win-x64 build
    3. Zips it to artifacts/GreenLumaPresets-v<version>-win-x64.zip
    4. Rewrites update.xml with the version, download URL, changelog URL and
       the SHA-256 checksum AutoUpdater.NET verifies before installing.

    Upload the zip to a GitHub release tagged v<version>, then commit update.xml.
    Clients pick up the update once update.xml reaches the main branch.

.EXAMPLE
    ./scripts/release.ps1
#>
[CmdletBinding()]
param(
    [string]$Repository = "AnsNihility/GreenLuma-Presets"
)

$ErrorActionPreference = "Stop"

$root = Split-Path -Parent $PSScriptRoot
$projectPath = Join-Path $root "GreenLumaPresets/GreenLumaPresets.csproj"
$updateXmlPath = Join-Path $root "update.xml"

[xml]$project = Get-Content $projectPath
$version = ($project.Project.PropertyGroup | Where-Object { $_.Version } | Select-Object -First 1).Version
if (-not $version) { throw "No <Version> found in $projectPath" }

$artifactsDir = Join-Path $root "artifacts"
$publishDir = Join-Path $artifactsDir "publish/v$version"
$zipName = "GreenLumaPresets-v$version-win-x64.zip"
$zipPath = Join-Path $artifactsDir $zipName

Write-Host "Publishing GreenLuma Presets v$version..."
if (Test-Path $publishDir) { Remove-Item -Recurse -Force $publishDir }
dotnet publish $projectPath -c Release -r win-x64 -o $publishDir -nologo
if ($LASTEXITCODE -ne 0) { throw "dotnet publish failed" }

Write-Host "Creating $zipName..."
if (Test-Path $zipPath) { Remove-Item -Force $zipPath }
Compress-Archive -Path (Join-Path $publishDir "*") -DestinationPath $zipPath

$checksum = (Get-FileHash -Algorithm SHA256 $zipPath).Hash

$updateXml = @"
<?xml version="1.0" encoding="utf-8"?>
<item>
  <!-- Generated by scripts/release.ps1 -->
  <version>$version.0</version>
  <url>https://github.com/$Repository/releases/download/v$version/$zipName</url>
  <changelog>https://github.com/$Repository/releases/tag/v$version</changelog>
  <!-- Verified by AutoUpdater.NET before the update is installed -->
  <checksum algorithm="SHA256">$checksum</checksum>
  <!-- Set to true to force update (users can't skip) -->
  <mandatory>false</mandatory>
</item>
"@
[System.IO.File]::WriteAllText($updateXmlPath, $updateXml.Replace("`r`n", "`n").Replace("`n", "`r`n"), (New-Object System.Text.UTF8Encoding $false))

Write-Host ""
Write-Host "Archive : $zipPath"
Write-Host "SHA-256 : $checksum"
Write-Host "Updated : $updateXmlPath"
Write-Host ""
Write-Host "Next: create the GitHub release v$version, upload the archive, then commit update.xml."
